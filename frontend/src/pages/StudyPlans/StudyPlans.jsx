import { useEffect, useState } from "react";
import DashboardLayout from "../../components/layout/DashboardLayout";
import PageTransition from "../../components/common/PageTransition";
import Modal from "../../components/ui/Modal";
import toast from "react-hot-toast";

// Import Lucide Icons for Premium UI
import { 
  CalendarDays, 
  Clock3, 
  BookOpen, 
  Eye, 
  FileDown, 
  Trash2, 
  BookMarked
} from "lucide-react";

import ReactMarkdown from "react-markdown";
import remarkGfm from "remark-gfm";
import rehypeHighlight from "rehype-highlight";
import "highlight.js/styles/github-dark.css";
import html2pdf from "html2pdf.js";

import {
  getStudyPlans,
  deleteStudyPlan,
} from "../../services/studyPlanService";

function StudyPlans() {
  const [plans, setPlans] = useState([]);
  const [selectedPlan, setSelectedPlan] = useState(null);

  const fetchPlans = async () => {
    try {
      const response = await getStudyPlans();
      setPlans(response.data);
    } catch (error) {
      console.error(error);
      toast.error("Failed to load study plans.");
    }
  };

  useEffect(() => {
    fetchPlans();
  }, []);

  const handleDelete = async (id) => {
    try {
      await deleteStudyPlan(id);
      toast.success("Study plan deleted.");
      fetchPlans();
    } catch (error) {
      console.error(error);
      toast.error("Failed to delete.");
    }
  };

  const handleExport = (plan) => {
    const element = document.createElement("div");

    element.innerHTML = `
    <div style="padding:40px;font-family:Arial,sans-serif;">
      <h1>StudentOS AI Study Plan</h1>
      <hr/>
      <h2>${plan.title}</h2>
      <p><strong>Exam Date:</strong> ${new Date(plan.examDate).toLocaleDateString()}</p>
      <p><strong>Study Hours:</strong> ${plan.studyHours} hrs/day</p>
      <p><strong>Subjects:</strong></p>
      <pre style="white-space:pre-wrap;font-size:14px;">${plan.subjects}</pre>
      <hr/>
      <h2>Generated Study Plan</h2>
      <pre style="white-space:pre-wrap;font-size:15px;">${plan.plan}</pre>
      <hr/>
      <p>Generated by StudentOS AI</p>
    </div>
  `;

    html2pdf()
      .set({
        margin: 10,
        filename: `${plan.title}.pdf`,
        image: { type: "jpeg", quality: 1 },
        html2canvas: { scale: 2 },
        jsPDF: { unit: "mm", format: "a4", orientation: "portrait" },
      })
      .from(element)
      .save();
  };

  // Dynamic Metrics Calculation for the Tiny Statistics Row
  const totalPlans = plans.length;
  const totalStudyHours = plans.reduce((acc, curr) => acc + (Number(curr.studyHours) || 0), 0);
  const totalSubjectsEstimated = plans.reduce((acc, curr) => {
    const lines = curr.subjects ? curr.subjects.split(/[,\n]/).filter(s => s.trim().length > 0) : [];
    return acc + (lines.length || 1);
  }, 0);

  return (
    <DashboardLayout>
      <PageTransition>
        <div className="mx-auto max-w-6xl space-y-8">
          
          {/* ⭐ 12. Page Header Upgrade (Removed small box counter) */}
          <div>
            <h1 className="text-4xl font-bold text-white tracking-tight">Saved Study Plans</h1>
            <p className="mt-2 text-slate-400">
              Review, export and manage your AI-generated study schedules.
            </p>
          </div>

          {/* ⭐ 11. Tiny Statistics Row */}
          <div className="grid grid-cols-1 gap-4 sm:grid-cols-3">
            <div className="p-4 rounded-3xl border border-slate-800 bg-gradient-to-br from-slate-900 via-slate-900 to-slate-950">
              <p className="text-xs font-semibold uppercase tracking-wider text-slate-500">Saved Plans</p>
              <p className="mt-1 text-2xl font-bold text-white">{totalPlans}</p>
            </div>
            <div className="p-4 rounded-3xl border border-slate-800 bg-gradient-to-br from-slate-900 via-slate-900 to-slate-950">
              <p className="text-xs font-semibold uppercase tracking-wider text-slate-500">Total Velocity</p>
              <p className="mt-1 text-2xl font-bold text-emerald-400">{totalStudyHours} hrs/day</p>
            </div>
            <div className="p-4 rounded-3xl border border-slate-800 bg-gradient-to-br from-slate-900 via-slate-900 to-slate-950">
              <p className="text-xs font-semibold uppercase tracking-wider text-slate-500">Tracked Subjects</p>
              <p className="mt-1 text-2xl font-bold text-yellow-400">{totalSubjectsEstimated}</p>
            </div>
          </div>

          {/* Empty State / Grid Render */}
          {plans.length === 0 ? (
            /* ⭐ 6. Better Empty State & Standardized Radius */
            <div className="rounded-3xl border border-slate-800 bg-gradient-to-br from-slate-900 via-slate-900 to-slate-950 p-16 text-center flex flex-col items-center">
              <div className="w-16 h-16 bg-slate-800/50 rounded-2xl flex items-center justify-center text-3xl mb-4">
                📚
              </div>
              <h2 className="text-2xl font-semibold text-white">
                No Saved Plans Yet
              </h2>
              <p className="mt-2 max-w-sm text-slate-400 text-sm">
                Generate your first AI study plan.
              </p>
              <a 
                href="/study-planner" 
                className="mt-6 rounded-xl bg-indigo-600 px-6 py-3 text-sm font-semibold text-white hover:bg-indigo-700 transition-colors shadow-lg shadow-indigo-600/20"
              >
                Generate Plan
              </a>
            </div>
          ) : (
            <div className="grid gap-6">
              {plans.map((plan) => (
                /* ⭐ 3, 4, 5, 10, 13. Advanced Premium Card Layout */
                <div
                  key={plan._id}
                  className="group relative rounded-3xl border border-slate-800 bg-gradient-to-br from-slate-900 via-slate-900 to-slate-950 p-6 border-l-4 border-l-indigo-500 shadow-sm transition-all duration-300 hover:-translate-y-1 hover:shadow-xl hover:shadow-indigo-500/10"
                >
                  <div className="flex flex-col justify-between gap-6 lg:flex-row lg:items-center">
                    
                    {/* Upper Left Meta Section */}
                    <div className="space-y-4 flex-1">
                      <h2 className="text-2xl font-bold tracking-tight text-white group-hover:text-indigo-400 transition-colors duration-300">
                        {plan.title}
                      </h2> 

                      {/* Icons & Badges Row Grid */}
                      <div className="flex flex-wrap items-center gap-4 text-sm">
                        {/* ⭐ 1. Lucide Replacement Tags & ⭐ 13. Uniform Radius */}
                        <div className="flex items-center gap-2 rounded-full bg-indigo-500/10 border border-indigo-500/10 px-3 py-1.5 font-medium text-indigo-300">
                          <CalendarDays className="h-4 w-4" />
                          <span>Exam: {new Date(plan.examDate).toLocaleDateString(undefined, { month: 'short', day: 'numeric' })}</span>
                        </div>

                        <div className="flex items-center gap-2 rounded-full bg-emerald-500/10 border border-emerald-500/10 px-3 py-1.5 font-medium text-emerald-300">
                          <Clock3 className="h-4 w-4" />
                          <span>{plan.studyHours} hrs/day</span>
                        </div>

                        <div className="flex items-center gap-2 rounded-full bg-yellow-500/10 border border-yellow-500/10 px-3 py-1.5 font-medium text-yellow-300">
                          <BookOpen className="h-4 w-4" />
                          <span className="max-w-[240px] truncate">Active Subjects</span>
                        </div>
                      </div>
                    </div>

                    {/* ⭐ 7, 9. Responsive & Identical Width Buttons Container */}
                    <div className="flex flex-col gap-3 w-full sm:flex-row sm:w-auto">
                      <button
                        onClick={() => setSelectedPlan(plan)}
                        className="inline-flex items-center justify-center gap-2 rounded-xl bg-indigo-600 px-5 py-3 text-sm font-semibold text-white hover:bg-indigo-700 transition-colors w-full sm:w-32"
                      >
                        <Eye className="h-4 w-4" /> View
                      </button>

                      <button
                        onClick={() => handleExport(plan)}
                        className="inline-flex items-center justify-center gap-2 rounded-xl bg-slate-800 px-5 py-3 text-sm font-semibold text-white border border-slate-700/50 hover:bg-slate-700 transition-colors w-full sm:w-32"
                      >
                        <FileDown className="h-4 w-4" /> Export PDF
                      </button>

                      <button
                        onClick={() => handleDelete(plan._id)}
                        className="inline-flex items-center justify-center gap-2 rounded-xl bg-red-950/40 border border-red-900/30 px-5 py-3 text-sm font-semibold text-red-400 hover:bg-red-900/40 transition-colors w-full sm:w-32"
                      >
                        <Trash2 className="h-4 w-4" /> Delete
                      </button>
                    </div>

                  </div>
                </div>
              ))}
            </div>
          )}

          {/* ⭐ 8, 13. Highly Detailed Professional Modular Architecture */}
          <Modal
            isOpen={selectedPlan !== null}
            title={selectedPlan?.title || ""}
            onClose={() => setSelectedPlan(null)}
          >
            {selectedPlan && (
              <div className="space-y-6">
                
                {/* Meta Summary Matrix Banner Inside Modal */}
                <div className="grid grid-cols-1 gap-3 sm:grid-cols-3 bg-slate-950/60 p-4 rounded-2xl border border-slate-800">
                  <div className="flex items-center gap-3">
                    <div className="p-2 bg-indigo-500/10 rounded-xl text-indigo-400">
                      <CalendarDays className="h-5 w-5" />
                    </div>
                    <div>
                      <p className="text-[11px] uppercase tracking-wider text-slate-500 font-bold">Exam Date</p>
                      <p className="text-sm font-semibold text-white">{new Date(selectedPlan.examDate).toLocaleDateString()}</p>
                    </div>
                  </div>

                  <div className="flex items-center gap-3">
                    <div className="p-2 bg-emerald-500/10 rounded-xl text-emerald-400">
                      <Clock3 className="h-5 w-5" />
                    </div>
                    <div>
                      <p className="text-[11px] uppercase tracking-wider text-slate-500 font-bold">Study Target</p>
                      <p className="text-sm font-semibold text-white">{selectedPlan.studyHours} hrs/day</p>
                    </div>
                  </div>

                  <div className="flex items-center gap-3">
                    <div className="p-2 bg-yellow-500/10 rounded-xl text-yellow-400">
                      <BookMarked className="h-5 w-5" />
                    </div>
                    <div>
                      <p className="text-[11px] uppercase tracking-wider text-slate-500 font-bold">Scope</p>
                      <p className="text-sm font-semibold text-white truncate max-w-[140px]">{selectedPlan.subjects || "All Syllabus"}</p>
                    </div>
                  </div>
                </div>

                <div className="border-t border-slate-800/80 my-2"></div>

                {/* Markdown Workspace Body */}
                <div className="prose prose-invert max-w-none prose-headings:text-white prose-p:text-slate-300 prose-li:text-slate-300 bg-slate-900/30 p-2 rounded-xl">
                  <ReactMarkdown
                    remarkPlugins={[remarkGfm]}
                    rehypePlugins={[rehypeHighlight]}
                  >
                    {selectedPlan.plan}
                  </ReactMarkdown>
                </div>
              </div>
            )}
          </Modal>

        </div>
      </PageTransition>
    </DashboardLayout>
  );
}

export default StudyPlans;