import { useEffect, useState } from "react";
import DashboardLayout from "../../components/layout/DashboardLayout";
import PageTransition from "../../components/common/PageTransition";
import Modal from "../../components/ui/Modal";
import toast from "react-hot-toast";

import ReactMarkdown from "react-markdown";
import remarkGfm from "remark-gfm";
import rehypeHighlight from "rehype-highlight";
import "highlight.js/styles/github-dark.css";
import html2pdf from "html2pdf.js";

import {
  getStudyPlans,
  deleteStudyPlan,
} from "../../services/studyPlanService";

function StudyPlans() {
  const [plans, setPlans] = useState([]);
  const [search, setSearch] = useState("");

  const [selectedPlan, setSelectedPlan] = useState(null);

  const fetchPlans = async () => {
    try {
      const response = await getStudyPlans();
      setPlans(response.data);
    } catch (error) {
      console.error(error);
      toast.error("Failed to load study plans.");
    }
  };

  useEffect(() => {
    fetchPlans();
  }, []);

  const handleDelete = async (id) => {
    try {
      await deleteStudyPlan(id);

      toast.success("Study plan deleted.");

      fetchPlans();
    } catch (error) {
      console.error(error);
      toast.error("Failed to delete.");
    }
  };

  const handleExport = (plan) => {
    const element = document.createElement("div");

    element.innerHTML = `
    <div style="padding:40px;font-family:Arial,sans-serif;">
      <h1>StudentOS AI Study Plan</h1>

      <hr/>

      <h2>${plan.title}</h2>

      <p><strong>Exam Date:</strong> ${new Date(
        plan.examDate,
      ).toLocaleDateString()}</p>

      <p><strong>Study Hours:</strong> ${plan.studyHours} hrs/day</p>

      <p><strong>Subjects:</strong></p>

      <pre style="white-space:pre-wrap;font-size:14px;">
${plan.subjects}
      </pre>

      <hr/>

      <h2>Generated Study Plan</h2>

      <pre style="white-space:pre-wrap;font-size:15px;">
${plan.plan}
      </pre>

      <hr/>

      <p>
        Generated by StudentOS AI
      </p>
    </div>
  `;

    html2pdf()
      .set({
        margin: 10,
        filename: `${plan.title}.pdf`,
        image: {
          type: "jpeg",
          quality: 1,
        },
        html2canvas: {
          scale: 2,
        },
        jsPDF: {
          unit: "mm",
          format: "a4",
          orientation: "portrait",
        },
      })
      .from(element)
      .save();
  };

  const filteredPlans = plans.filter((plan) =>
    `${plan.title} ${plan.subjects}`
      .toLowerCase()
      .includes(search.toLowerCase()),
  );

  return (
    <DashboardLayout>
      <PageTransition>
        <div className="mx-auto max-w-6xl space-y-8">
          <div>
            <h1 className="text-4xl font-bold text-white">Saved Study Plans</h1>

            <p className="mt-2 text-slate-400">
              Access all your AI-generated study plans.
            </p>
          </div>

          <input
            value={search}
            onChange={(e) => setSearch(e.target.value)}
            placeholder="Search study plans..."
            className="w-full rounded-xl border border-slate-700 bg-slate-900 p-4 text-white outline-none focus:border-indigo-500"
          />

          {filteredPlans.length === 0 ? (
            <div className="rounded-3xl border border-slate-800 bg-slate-900 p-12 text-center">
              <h2 className="text-2xl font-semibold text-white">
                No Study Plans Found
              </h2>

              <p className="mt-3 text-slate-400">
                Generate and save your first AI study plan.
              </p>
            </div>
          ) : (
            <div className="grid gap-6">
              {filteredPlans.map((plan) => (
                <div
                  key={plan._id}
                  className="rounded-3xl border border-slate-800 bg-slate-900 p-6 transition hover:border-indigo-500"
                >
                  <div className="flex flex-col gap-5 lg:flex-row lg:items-center lg:justify-between">
                    <div>
                      <h2 className="text-2xl font-bold text-white">
                        {plan.title}
                      </h2>

                      <div className="mt-3 flex flex-wrap gap-3">
                        <span className="rounded-full bg-indigo-500/20 px-3 py-1 text-sm text-indigo-300">
                          📅 {new Date(plan.examDate).toLocaleDateString()}
                        </span>

                        <span className="rounded-full bg-emerald-500/20 px-3 py-1 text-sm text-emerald-300">
                          ⏱ {plan.studyHours} hrs/day
                        </span>

                        <span className="rounded-full bg-yellow-500/20 px-3 py-1 text-sm text-yellow-300">
                          📚 Subjects
                        </span>
                      </div>
                    </div>

                    <div className="flex flex-wrap gap-3">
                      <button
                        onClick={() => setSelectedPlan(plan)}
                        className="rounded-xl bg-indigo-600 px-5 py-3 font-semibold text-white hover:bg-indigo-700"
                      >
                        👁 View
                      </button>

                      <button
                        onClick={() => handleExport(plan)}
                        className="rounded-xl bg-slate-700 px-5 py-3 font-semibold text-white transition hover:bg-slate-600"
                      >
                        📄 Export PDF
                      </button>

                      <button
                        onClick={() => handleDelete(plan._id)}
                        className="rounded-xl bg-red-600 px-5 py-3 font-semibold text-white hover:bg-red-700"
                      >
                        🗑 Delete
                      </button>
                    </div>
                  </div>
                </div>
              ))}
            </div>
          )}

          <Modal
            isOpen={selectedPlan}
            title={selectedPlan?.title || ""}
            onClose={() => setSelectedPlan(null)}
          >
            {selectedPlan && (
              <div className="space-y-6">
                <div className="flex flex-wrap gap-3">
                  <span className="rounded-full bg-indigo-500/20 px-3 py-1 text-sm text-indigo-300">
                    📅 {new Date(selectedPlan.examDate).toLocaleDateString()}
                  </span>

                  <span className="rounded-full bg-emerald-500/20 px-3 py-1 text-sm text-emerald-300">
                    ⏱ {selectedPlan.studyHours} hrs/day
                  </span>
                </div>

                <div className="prose prose-invert max-w-none prose-headings:text-white prose-p:text-slate-300 prose-li:text-slate-300">
                  <ReactMarkdown
                    remarkPlugins={[remarkGfm]}
                    rehypePlugins={[rehypeHighlight]}
                  >
                    {selectedPlan.plan}
                  </ReactMarkdown>
                </div>
              </div>
            )}
          </Modal>
        </div>
      </PageTransition>
    </DashboardLayout>
  );
}

export default StudyPlans;
